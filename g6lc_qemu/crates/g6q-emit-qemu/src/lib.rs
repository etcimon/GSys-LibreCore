//! `g6q-emit-qemu` — backends **B1** (machine, CPU, devices) and **B2** (TCG plugins).
//!
//! # The boundary this crate exists on
//!
//! QEMU is GPL-2.0 and this package is MIT. Both facts survive because of one structural
//! rule, enforced by `tools/check_independence.py` and restated here because this is the
//! crate where it would be violated:
//!
//! > **The generator writes text. It never links, includes, binds or vendors QEMU.**
//!
//! The C this crate produces *is* part of a GPL work and therefore carries GPL terms —
//! emitting an MIT header into a QEMU tree would be the actual mistake. Output goes to
//! gitignored directories and is never tracked here
//! ([`AGENTS-licensing.md`] §2).
//!
//! # Stage
//!
//! Q0 implements the file header contract — the part that is a licensing correctness
//! question rather than a code-generation question — plus the emitted-file model. Q4
//! adds the machine, CPU and device emitters; Q5/Q7 add the plugins.
//!
//! [`AGENTS-licensing.md`]: ../../../AGENTS-licensing.md

