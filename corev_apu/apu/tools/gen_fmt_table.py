"""Format table from the pinned Vulkan registry (plan pass P3, step 1).

The registry's <formats> block already states, for every VkFormat, the
block size, texels per block, packing, compression scheme and each
component's name, width and numeric class.  This tool makes that the one
description of a format:

  gen_fmt_table.py            write tools/vk_formats.py (generated table)
  gen_fmt_table.py --check    rc 1 if vk_formats.py is stale, or if a
                              [formats] row of vn_device_profile.toml
                              disagrees with the registry (bpp, comps,
                              uint, flt, half, bgr, srgb)

It does not generate RTL.  The engines still carry their own format
cases; the audit only guarantees the profile's hand-typed shape fields
cannot drift from the registry.
"""
import os
import sys
import tomllib
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
VKXML = os.path.join(ROOT, 'specs', 'venus-protocol', 'xmls', 'vk.xml')
OUT = os.path.join(HERE, 'vk_formats.py')
PROFILE = os.path.join(HERE, 'vn_device_profile.toml')


def load():
    """-> [(name, value, block_bytes, texels, packed, compressed,
            ((comp, bits, numeric), ...))] in VkFormat value order."""
    root = ET.parse(VKXML).getroot()
    val = {}
    for e in root.iter('enums'):
        if e.get('name') == 'VkFormat':
            for m in e.iter('enum'):
                if m.get('value') is not None:
                    val[m.get('name')] = int(m.get('value'), 0)
    # extension formats: value = 1e9 + (extnumber-1)*1000 + offset
    for ext in root.iter('extension'):
        for m in ext.iter('enum'):
            if m.get('extends') == 'VkFormat' and m.get('offset'):
                n = int(m.get('extnumber') or ext.get('number'))
                val[m.get('name')] = 1000000000 + (n - 1) * 1000 + \
                    int(m.get('offset'))
    for feat in root.iter('feature'):
        for m in feat.iter('enum'):
            if m.get('extends') == 'VkFormat' and m.get('offset'):
                n = int(m.get('extnumber'))
                val[m.get('name')] = 1000000000 + (n - 1) * 1000 + \
                    int(m.get('offset'))
    rows = []
    for f in root.iter('format'):
        name = f.get('name')
        comps = tuple(
            (c.get('name'),
             0 if c.get('bits') == 'compressed' else int(c.get('bits')),
             c.get('numericFormat')) for c in f.iter('component'))
        rows.append((name[len('VK_FORMAT_'):], val.get(name, -1),
                     int(f.get('blockSize')), int(f.get('texelsPerBlock')),
                     int(f.get('packed') or 0), f.get('compressed') or '',
                     comps))
    rows.sort(key=lambda r: (r[1], r[0]))
    return rows


def render(rows):
    L = ['#!/usr/bin/env python3',
         '# Copyright 2026 Etienne Cimon',
         '# SPDX-License-Identifier: MIT',
         '"""GENERATED by gen_fmt_table.py from the pinned vk.xml - do not '
         'edit.',
         '',
         'FORMATS[name] = (value, block_bytes, texels_per_block, '
         'packed_bits,',
         '                 compression, ((component, bits, numeric), ...)).',
         'bits is 0 for a compressed component."""',
         '',
         'FORMATS = {']
    for (n, v, bs, tp, pk, cp, comps) in rows:
        L.append('    %r: (%d, %d, %d, %d, %r,' % (n, v, bs, tp, pk, cp))
        L.append('        %r),' % (comps,))
    L += ['}', '',
          '',
          'def aspects(name):',
          '    """\'color\', \'depth\', \'stencil\' or \'depth+stencil\'."""',
          '    c = {x[0] for x in FORMATS[name][5]}',
          "    if 'D' in c or 'S' in c:",
          "        return '+'.join(a for a, k in (('depth', 'D'), "
          "('stencil', 'S'))",
          '                        if k in c)',
          "    return 'color'",
          '']
    return '\n'.join(L)


def audit_profile(rows):
    """profile [formats] shape fields vs the registry."""
    reg = {r[0]: r for r in rows}
    prof = tomllib.load(open(PROFILE, 'rb')).get('formats', {})
    bad = 0
    for nm, ent in prof.items():
        if not isinstance(ent, dict):
            continue
        r = reg.get(nm)
        if r is None:
            print('FINDING %s: not a registry format' % nm)
            bad += 1
            continue
        _, _, bs, tp, pk, cp, comps = r
        color = [c for c in comps if c[0] in 'RGBA']
        ds = [c for c in comps if c[0] in 'DS']
        exp = dict(
            bpp=bs,
            # depth/stencil rows describe the depth plane the engines read
            comps=len(color) if color else 1,
            uint=int(bool(color) and all(c[2] == 'UINT' for c in color)),
            flt=int(all(c[2] == 'SFLOAT' and c[1] == 32
                        for c in (color or ds[:1]))),
            half=int(bool(color) and all(c[2] == 'SFLOAT' and c[1] == 16
                                         for c in color)),
            bgr=int(len(color) >= 3 and color[0][0] == 'B'),
            srgb=int(any(c[2] == 'SRGB' for c in color)))
        got = dict(bpp=int(ent.get('bpp', 4)), comps=int(ent.get('comps', 4)),
                   uint=int(ent.get('uint', 0)), flt=int(ent.get('flt', 0)),
                   half=int(ent.get('half', 0)), bgr=int(ent.get('bgr', 0)),
                   srgb=int(ent.get('srgb', 0)))
        for k in exp:
            if exp[k] != got[k]:
                bad += 1
                print('FINDING %s.%s: profile %d, registry %d' % (
                    nm, k, got[k], exp[k]))
    print('formats: %d registry rows, %d profile rows, %d findings' % (
        len(rows), sum(isinstance(e, dict) for e in prof.values()), bad))
    return bad


def main():
    rows = load()
    text = render(rows)
    if '--check' in sys.argv:
        bad = 0
        old = open(OUT, encoding='utf-8').read().replace('\r\n', '\n') \
            if os.path.exists(OUT) else ''
        if old != text:
            print('DRIFT vk_formats.py is stale (run gen_fmt_table.py)')
            bad += 1
        bad += audit_profile(rows)
        return 1 if bad else 0
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote %s (%d formats)' % (os.path.relpath(OUT, ROOT), len(rows)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
