    /// BalanceMux snippets stay early so origin RHS rewrite can see staged wires.
    #[test]
    fn balance_mux_snippet_injects_before_first_process() {
        let src = r#"module bm_mod (
    input logic a, b, c,
    output logic y
);
  logic t;
  always_comb begin
    t = a | b;
    y = t;
  end
endmodule
"#;
        let snippet = "  // --- BalanceMux arm staging (latency-neutral) ---\n  logic [63:0] svt_bm_top_p1_n0;\n  always_comb begin : svt_bm_top_p1_n0_stage\n    svt_bm_top_p1_n0 = a | b;\n  end\n";
        let mut trace = EditTrace::new();
        trace.record_edit(EditRecord {
            id: 0,
            kind: EditKind::BalanceMux,
            origin: SourceLoc {
                file: "bm_mod.sv".into(),
                start_line: 7,
                start_col: 1,
                end_line: 7,
                end_col: 1,
                byte_start: 0,
                byte_end: 0,
                origin: OriginKind::UserFile,
            },
            path_id: Some(1),
            node_id: Some(0),
            new_name: Some("svt_bm_top_p1_n0".into()),
            fo4_before: Some(20.0),
            fo4_after: Some(10.0),
            rationale: "stage".into(),
            emit_rhs: Some("svt_bm_top_p1_n0".into()),
            emit_rhs_extras: Vec::new(),
            emit_snippet: Some(snippet.into()),
        });
        // Lean default: BalanceMux credit-only (no RTL).
        let lean = apply_edits_to_source(src, &trace, &EmitPolicy::default());
        assert!(
            lean.contains("review-only credit") || !lean.contains("svt_bm_top_p1_n0_stage"),
            "lean demotes BalanceMux RTL"
        );
        // Opt-in structural BalanceMux early inject.
        let mut dense = dense_options_from_source(src);
        dense.emit_balance_mux_rtl = true;
        let text = apply_edits_to_source_dense(src, &trace, &EmitPolicy::default(), &dense);
        assert!(
            text.contains("svt_bm_top_p1_n0_stage"),
            "unique block label expected with emit_balance_mux_rtl"
        );
        let early = text
            .find("BEGIN sv-timing auto-correct (balance_mux rewrite)")
            .expect("balance_mux early");
        let first_proc = text.find("always_comb begin").expect("first process");
        assert!(
            early < first_proc || text[..first_proc].contains("svt_bm_top_p1_n0"),
            "BalanceMux staging must be early"
        );
    }
