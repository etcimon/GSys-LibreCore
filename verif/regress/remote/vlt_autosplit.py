"""Generate a Verilator control file (split_var) from a `--report-unoptflat` lint log.

Every UNOPTFLAT (false combinational loop through a packed aggregate) that Verilator
breaks costs a change-detection trigger and extra act-region iterations per eval
step. `--report-unoptflat` lists, per loop, the variables whose splitting would
remove the loop ("can split_var"). This tool turns that report into `.vlt`
`split_var -module M -var V` entries so the fix lives in a control file, not in
the RTL.

usage:
  vlt_autosplit.py LINT_LOG [--merge EXISTING.vlt] [--min-loops N] [--exclude REGEX] -o OUT.vlt

The module is taken from the file name of the candidate (modules are declared in
files of the same name in this repository); the variable is the last path element.
Candidates are ranked by (loops they appear in, circular fanout). Entries already
present in --merge are kept once. Verilator reports any entry it cannot honour as
SPLITVAR at build time (dynamic bit ranges, hierarchical dot references, 1-bit).
"""
import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

CAND = re.compile(
    r"^\s*(?:/[^ :]*/)?([^/ :]+)\.sv:\d+:\d+:\s+(\S+), width (\d+), circular fanout (\d+)(.*)$")
ENTRY = re.compile(r'^\s*split_var\s+-module\s+"([^"]+)"\s+-var\s+"([^"]+)"')


def parse(log: Path):
    cands = defaultdict(lambda: {"width": 0, "fanout": 0, "loops": 0})
    for line in log.read_text(errors="replace").splitlines():
        m = CAND.match(line)
        if not m or "can split_var" not in m.group(5):
            continue
        module, path, width, fanout = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
        var = path.rsplit(".", 1)[-1]
        var = re.sub(r"^__Vcell(?:inp|out)__[^_]*__", "", var)
        if var.startswith("__Vdfg") or "[" in var:
            continue
        c = cands[(module, var)]
        c["width"] = max(c["width"], width)
        c["fanout"] += fanout
        c["loops"] += 1
    return cands


def existing(vlt: Path):
    keep = set()
    if vlt and vlt.exists():
        for line in vlt.read_text().splitlines():
            m = ENTRY.match(line)
            if m:
                keep.add((m.group(1), m.group(2)))
    return keep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("log", type=Path)
    ap.add_argument("--merge", type=Path, default=None)
    ap.add_argument("--min-loops", type=int, default=1)
    ap.add_argument("--exclude", default=None, help="regex on 'module var' to skip")
    ap.add_argument("-o", "--out", type=Path, required=True)
    a = ap.parse_args()
    cands = parse(a.log)
    keep = existing(a.merge)
    excl = re.compile(a.exclude) if a.exclude else None
    ranked = sorted(cands.items(), key=lambda kv: (-kv[1]["loops"], -kv[1]["fanout"]))
    lines = []
    if a.merge and a.merge.exists():
        lines.append(a.merge.read_text().rstrip("\n"))
        lines.append("")
        lines.append("// --- generated by vlt_autosplit.py from %s" % a.log.name)
    else:
        lines.append("`verilator_config")
        lines.append("// generated by vlt_autosplit.py from %s" % a.log.name)
    n = 0
    for (module, var), c in ranked:
        if c["loops"] < a.min_loops or (module, var) in keep:
            continue
        if excl and excl.search(f"{module} {var}"):
            continue
        lines.append('split_var -module "%s" -var "%s"  // width %d, loops %d, fanout %d'
                     % (module, var, c["width"], c["loops"], c["fanout"]))
        n += 1
    a.out.write_text("\n".join(lines) + "\n")
    print(f"{n} new split_var entries ({len(keep)} kept from merge) -> {a.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
