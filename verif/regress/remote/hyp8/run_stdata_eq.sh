# r127: sweep equivalence of the store_unit store-data forms. The bench is
# GENERATED from the module text (the three permutation functions, the
# gen_st_byte lane block and the reference expression are sliced out of
# core/store_unit.sv), so it checks the code that is in the tree: every fu_op x
# address offset x mbe, AMO flag derived from the op as in the module, over a
# distinct-byte word and random words. Second pass is a negative control (the
# sliced lane text is mutated; it must FAIL).
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
HYP="${STDATA_HYP_CORE:-$ROOT/build-platform/workspace/hyp/hyp_redesign_core_8fo4/core}"
OUT="${STDATA_EQ_OUT:-$ROOT/build-platform/workspace/build/hyp8-stdata-eq}"
rcsum=0
for v in plain mut; do
  mkdir -p "$OUT/$v"
  python3 - "$HYP/store_unit.sv" "$OUT/$v/tb.sv" "$v" <<'PY'
import sys
src=open(sys.argv[1],encoding='utf-8').read().replace('\r\n','\n')
def cut(a,b,inc_b=False):
    i=src.index(a); j=src.index(b,i)
    return src[i:j+(len(b) if inc_b else 0)]
fa="  function automatic logic [7:0] store_byte_at("
fz=src.index("endfunction", src.index("function automatic logic [G6LCCfg.XLEN-1:0] store_data_fused("))+len("endfunction")
funcs=src[src.index(fa):fz]
lanes=cut("  localparam int unsigned ST_NB   = G6LCCfg.XLEN / 8;","  //pragma translate_off\n  logic [G6LCCfg.XLEN-1:0] rf_st_data;")
ref=cut("  logic [G6LCCfg.XLEN-1:0] rf_st_data;","  always_ff @(posedge clk_i) begin")
if sys.argv[3]=='mut':
    old="return (base < wb) ? (wb - 1 - base) : base;"
    assert lanes.count(old)==1
    lanes=lanes.replace(old,"return (base < wb) ? (wb - base) % 8 : base;")
tb=f"""// generated by verif/regress/remote/hyp8/run_stdata_eq.sh from core/store_unit.sv
package stdata_tb_pkg;
  import g6lc_core_pkg::*;
  typedef struct packed {{ int unsigned XLEN; bit IS_XLEN64; bit RVA; bit RVZiCboz; }} cfg_t;
  typedef struct packed {{ logic [63:0] data; fu_op operation; logic [63:0] vaddr; }} ctrl_t;
endpackage
// the two forms behind ports (same-module stimulus is not re-evaluated reliably
// by the local simulator; a port boundary is, as in the other r127 miters)
module stdata_forms import g6lc_core_pkg::*; import stdata_tb_pkg::*; (
    input  ctrl_t       lsu_ctrl_i,
    input  logic        mbe_i,
    output logic [63:0] lanes_o, ref_o
);
  localparam cfg_t G6LCCfg = '{{XLEN: 64, IS_XLEN64: 1'b1, RVA: 1'b1, RVZiCboz: 1'b1}};
  logic instr_is_amo;
  assign instr_is_amo = is_amo(lsu_ctrl_i.operation);
{funcs}
{lanes}
{ref}
  assign lanes_o = st_data_lane;
  assign ref_o   = rf_st_data;
endmodule

module tb_g6lc_hyp8_stdata_eq;
  import g6lc_core_pkg::*;
  import stdata_tb_pkg::*;
  // stimulus in plain variables; the struct port is one continuous assignment
  logic [63:0] s_data, s_vaddr;
  fu_op        s_op;
  ctrl_t lsu_ctrl_i;
  assign lsu_ctrl_i = '{{data: s_data, operation: s_op, vaddr: s_vaddr}};
  logic  mbe_i;
  logic [63:0] st_data_lane, rf_st_data;
  stdata_forms u (.lsu_ctrl_i(lsu_ctrl_i), .mbe_i(mbe_i), .lanes_o(st_data_lane), .ref_o(rf_st_data));
  int unsigned checked = 0, bad = 0, nops = 0;
  initial begin
    fu_op op;
    op = op.first();
    forever begin
      nops++;
      for (int unsigned o = 0; o < 8; o++)
        for (int unsigned m = 0; m < 2; m++)
          for (int unsigned d = 0; d < 6; d++) begin
            s_op    = op;
            s_vaddr = 64'(o) | (64'($urandom()) << 3);
            s_data  = (d == 0) ? 64'h8877665544332211 : {{$urandom(), $urandom()}};
            mbe_i = 1'(m);
            #1;
            checked++;
            if (st_data_lane !== rf_st_data) begin
              bad++;
              if (bad < 6) $display("FAIL op=%0d off=%0d mbe=%0d data=%h lanes=%h ref=%h",
                                    op, o, m, lsu_ctrl_i.data, st_data_lane, rf_st_data);
            end
          end
      if (op == op.last()) break;
      op = op.next();
    end
    if (bad == 0 && checked != 0) $display("HYP8_STDATA_EQ_PASS ops=%0d checked=%0d", nops, checked);
    else $display("HYP8_STDATA_EQ_FAIL ops=%0d checked=%0d bad=%0d", nops, checked, bad);
    $finish;
  end
endmodule
"""
open(sys.argv[2],'w',encoding='utf-8',newline='\n').write(tb)
PY
  if ! "${VERILATOR:-verilator}" --binary --timing -Wno-fatal -DG6LC_FETCH_B -I"$HYP/include" --Mdir "$OUT/$v/model" --top-module tb_g6lc_hyp8_stdata_eq "$HYP/include/config_pkg.sv" "$HYP/include/build_config_pkg.sv" "$HYP/include/g6lc_hyp_pkg.sv" "$HYP/include/g6lc64_hyp8_config_pkg.sv" "$HYP/include/riscv_pkg.sv" "$HYP/include/g6lc_core_pkg.sv" "$OUT/$v/tb.sv" > "$OUT/$v/build.log" 2>&1; then
    echo "[$v] BUILD FAIL $(grep -m3 '%Error' "$OUT/$v/build.log" | cut -c1-200)"; rcsum=1; continue
  fi
  line="$("$OUT/$v/model/Vtb_g6lc_hyp8_stdata_eq" | grep -E 'HYP8_STDATA_EQ' | head -1)"
  echo "[$v] $line"
  if [ "$v" = plain ]; then echo "$line" | grep -q _PASS || rcsum=1; else echo "$line" | grep -q _FAIL || rcsum=1; fi
done
exit $rcsum
