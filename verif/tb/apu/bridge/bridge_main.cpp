// 3d-b RTL bridge server (apu-vulkan-engine.md §12.3 phase B):
// clocks the real g6lc_apu_sys (ApuVenus, or ApuP1Transport with
// -GVenusOff=1) one cycle at a time and bridges it to a unix-domain
// stream socket — QEMU's g6lc_apu_bridge device (or bridge_selftest.py)
// is the CPU.
//
// Wire protocol (little-endian, see §12.3/3d-b):
//   u32 len (bytes after this field), u8 type, u8 flags, u16 seq, payload
//   QEMU->RTL:  0x01 MMIO_RD {u32 off}             -> 0x81 {u32 data,u8 err}
//               0x02 MMIO_WR {u32 off,u32 data,u8 strb} -> 0x82 {u8 err}
//   RTL->QEMU:  0x11 DMA_RD {u64 addr,u32 len}     -> 0x91 {u8 err,bytes}
//               0x12 DMA_WR {u64 addr,u32 len,bytes,strb[len/8 ceil]}
//                                                   -> 0x92 {u8 err}
//               0x13 IRQ {u8 level}                (no reply)
// The DUT keeps clocking while a DMA reply is outstanding; MMIO frames
// arriving meanwhile are queued.  seq matches replies to requests.
//
// Debug overlay: MMIO_RD offsets >= VN_MMIO_LEN+0x1000 (never generated
// by QEMU's 4 KiB region) read the vgsys observability taps
// (dbg_sel_i/dbg_rdata_o in the fixture) without touching the DUT —
// the selftest's chkp equivalents (EK_LIVE/EK_PAGES/EK_FENCE/EK_EXTRA/
// EK_HEAD/EK_STATUS) go through that page.
//
// Options: --sock PATH (env G6LC_APU_RTL_SOCK, default
// /tmp/g6lc-apu-rtl.sock), --trace FILE.fst, --max-cycles N,
// --bench N (free-run N cycles, print kHz), --stats (periodic counters).

