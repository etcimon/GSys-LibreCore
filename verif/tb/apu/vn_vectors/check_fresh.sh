# Oracle freshness: regenerate every session regen_vectors.sh knows into
# a scratch directory and compare with the files beside this script.
# A stored expectation that the generator no longer produces is stale
# even while its bench still passes (invariant I4 of the plan).
#
#   bash verif/tb/apu/vn_vectors/check_fresh.sh          # report, rc 1 on drift
#   bash verif/tb/apu/vn_vectors/check_fresh.sh --apply  # copy the fresh files in
#
# About six minutes.  Needs the pinned kernel uapi header under
# g6lc_qemu/linux-dist (so it is a developer and leaf check, not a CI
# lane).  *.hex is ignored by git: --apply refreshes those too, which is
# what a remote leaf ships.  Sessions on disk that regen_vectors.sh does
# not generate are listed, not judged.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
SCRATCH="${APU_VN_FRESH_DIR:-$(mktemp -d)}"
mkdir -p "$SCRATCH"
APU_VN_VEC_DIR="$SCRATCH" bash "$HERE/regen_vectors.sh" > "$SCRATCH/regen.log" 2>&1 || {
  tail -n 20 "$SCRATCH/regen.log"; echo "FRESH: regeneration failed"; exit 2; }
same=0; drift=0; names=""
for f in "$SCRATCH"/*; do
  b="$(basename "$f")"
  case "$b" in regen.log) continue ;; esac
  if [ -f "$HERE/$b" ] && cmp -s "$f" "$HERE/$b"; then
    same=$((same+1))
  else
    drift=$((drift+1)); names="$names ${b%.*}"
    if [ "${1:-}" = "--apply" ]; then cp "$f" "$HERE/$b"; fi
  fi
done
uncovered=0
for f in "$HERE"/*.exp; do
  [ -f "$SCRATCH/$(basename "$f")" ] || uncovered=$((uncovered+1))
done
echo "FRESH: $same files current, $drift drifted, $uncovered .exp on disk not generated by regen_vectors.sh"
if [ "$drift" -ne 0 ]; then
  echo "FRESH: drifted sessions:$(printf '%s\n' $names | sort -u | tr '\n' ' ')"
  if [ "${1:-}" = "--apply" ]; then echo "FRESH: applied"; exit 0; fi
  exit 1
fi
