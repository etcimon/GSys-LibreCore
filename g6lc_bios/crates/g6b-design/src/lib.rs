fn emit_connectors(spec: &BoardSpec) -> String {
    let mut out = String::from("// Generated connectors — symbols exist only when live\n");
    for name in spec
        .connectors
        .core
        .iter()
        .chain(spec.connectors.apu.iter())
        .chain(spec.connectors.uncore.iter())
    {
        match name.as_str() {
            "sbi" => out.push_str("extern INative SbiPutchar(INative ch);\n"),
            "pmu" => out.push_str("extern INative PmuRead(INative idx);\n"),
            "opp" => out.push_str("extern INative OppSet(U8 *id);\n"),
            "uart" => out.push_str("extern INative UartPut(U8 ch);\n"),
            "gpio" => out.push_str("extern INative GpioRead(INative pin);\n"),
            "spi" => out.push_str("extern INative SpiRead(INative off, U8 *dst, INative n);\n"),
            "net" => out.push_str("extern INative NetSend(U8 *buf, INative n);\n"),
            "clint" | "aclint" => out.push_str("extern INative ClintTime();\n"),
            "plic" => out.push_str("extern INative PlicClaim();\n"),
            "ddr" | "litedram" | "dram" => out.push_str("extern INative DramProbe();\n"),
            "pcie" | "pci" => {
                out.push_str("extern INative PciCfgRead(INative bdf, INative off);\n")
            }
            "eth" | "ethernet" => out.push_str("extern INative EthStatus();\n"),
            "sata" | "nvme" | "sd" | "storage" => {
                out.push_str("extern INative BlkRead(INative lba, U8 *dst, INative n);\n")
            }
            "hdmi" | "displayport" | "dp" => out.push_str("extern INative HdmiEdid(U8 *dst);\n"),
            _ => {
                out.push_str("// unknown connector `");
                out.push_str(name);
                out.push_str("`\n");
            }
        }
    }
    for p in &spec.peripherals {
        if p.class == "ai-island" {
            out.push_str("extern INative AiCapRead(INative off);\n");
        }
    }
    if spec.holyc.dual_band.tcp.enable {
        out.push_str("extern INative HolycReplPut(U8 *buf, INative n);\n");
        out.push_str("extern INative HolycReplGet(U8 *buf, INative n);\n");
    }
    if spec.loopback.enable {
        out.push_str("extern INative MboxDoorbell(INative op);\n");
        out.push_str("extern INative MboxPut(U8 *buf, INative n);\n");
        out.push_str("extern INative MboxGet(U8 *buf, INative n);\n");
    }
    if spec.postboot.enable != g6b_spec::PostbootMode::Never {
        out.push_str("extern INative SbiSrst(INative typ);\n");
    }
    if spec.uncore.clint && !out.contains("ClintTime") {
        out.push_str("extern INative ClintTime();\n");
    }
    if spec.uncore.plic && !out.contains("PlicClaim") {
        out.push_str("extern INative PlicClaim();\n");
    }
    if spec.uncore.ddr && !out.contains("DramProbe") {
        out.push_str("extern INative DramProbe();\n");
    }
    if spec.uncore.pcie && !out.contains("PciCfgRead") {
        out.push_str("extern INative PciCfgRead(INative bdf, INative off);\n");
    }
    if spec.uncore.ethernet && !out.contains("EthStatus") {
        out.push_str("extern INative EthStatus();\n");
    }
    if spec.uncore.storage && !out.contains("BlkRead") {
        out.push_str("extern INative BlkRead(INative lba, U8 *dst, INative n);\n");
    }
    if spec.uncore.hdmi && !out.contains("HdmiEdid") {
        out.push_str("extern INative HdmiEdid(U8 *dst);\n");
    }
    out
}

fn emit_mem(spec: &BoardSpec) -> String {
    if spec.rvv_live() {
        String::from(
            "// Generated MemCpy — HolyC; RISC-V in MemCpy.S (ISEL-RVV)\n\
             U0 MemCpy(U8 *dst, U8 *src, INative n)\n\
             {\n\
             \twhile (n) { *dst++ = *src++; n--; }\n\
             }\n",
        )
    } else {
        String::from(
            "// Generated MemCpy — HolyC; RISC-V in MemCpy.S (ISEL-SCALAR)\n\
             U0 MemCpy(U8 *dst, U8 *src, INative n)\n\
             {\n\
             \twhile (n) { *dst++ = *src++; n--; }\n\
             }\n",
        )
    }
}

fn emit_memcpy_s(spec: &BoardSpec) -> String {
    g6b_asm::analyze::libcalls(spec).to_asm()
}

fn emit_timer_s(spec: &BoardSpec) -> String {
    g6b_asm::analyze::timer(spec).to_asm()
}

fn emit_linker(spec: &BoardSpec) -> String {
    format!(
        "/* Generated linker script: DRAM {} len {} text_offset {} XLEN {} */\n\
         OUTPUT_ARCH(riscv)\n\
         ENTRY(_start)\n\
         SECTIONS {{\n\
         \t. = {};\n\
         \t.text : {{ *(.text.start) *(.text*) }}\n\
         \t.rodata : {{ *(.rodata*) }}\n\
         \t.data : {{ *(.data*) }}\n\
         \t.bss : {{ *(.bss*) }}\n\
         }}\n",
        spec.dram_base, spec.dram_len, spec.text_offset, spec.isa.xlen, spec.dram_base,
    )
}

fn emit_kmain(spec: &BoardSpec) -> String {
    let port = spec.holyc.dual_band.tcp.host_port;
    let dual = if spec.holyc.dual_band.tcp.enable && spec.holyc.dual_band.uart {
        format!("\tPrint(\"DUAL-BAND uart+tcp:{port}\\n\");\n")
    } else if spec.holyc.dual_band.tcp.enable {
        format!("\tPrint(\"DUAL-BAND tcp:{port}\\n\");\n")
    } else if spec.holyc.dual_band.uart {
        String::from("\tPrint(\"DUAL-BAND uart\\n\");\n")
    } else {
        String::new()
    };
    let init = if spec.holyc.fast_init {
        "\tHolycInit();\n"
    } else {
        ""
    };
    let gr = if spec.kernel.gr.enable {
        format!(
            "U0 SysGrInit()\n\
             {{\n\
             \tPrint(\"GR-INIT {}x{}x{} backend={}\\n\");\n\
             }}\n\
             \n",
            spec.kernel.gr.w, spec.kernel.gr.h, spec.kernel.gr.colors, spec.kernel.gr.backend
        )
    } else {
        String::from(
            "U0 SysGrInit()\n\
             {\n\
             \tPrint(\"GR-OFF\\n\");\n\
             }\n\
             \n",
        )
    };
    format!(
        "// Generated KMain.ZC — rust g6b-design, do not edit\n\
         // product={} march={} xlen={}\n\
         U0 HolycInit()\n\
         {{\n\
         \tPrint(\"HOLYC-READY\\n\");\n\
         }}\n\
         \n\
         U0 UiBoot()\n\
         {{\n\
         \tPrint(\"UI-BOOT\\n\");\n\
         }}\n\
         \n\
         {gr}\
         U0 TimerInit()\n\
         {{\n\
         \tPrint(\"TIMER-READY SBI-TIME\\n\");\n\
         }}\n\
         \n\
         U0 KMain()\n\
         {{\n\
         \tPrint(\"G6LC-BIOS\\n\");\n\
         {init}\
         {dual}\
         \tSysGrInit();\n\
         \tTimerInit();\n\
         \tUiBoot();\n\
         }}\n",
        spec.product, spec.isa.march, spec.isa.xlen
    )
}

fn emit_adam(spec: &BoardSpec) -> String {
    format!(
        "// Generated Adam.ZC — Temple/ZealOS first task (product={})\n\
         U0 Adam()\n\
         {{\n\
         \tKMain();\n\
         }}\n",
        spec.product
    )
}

fn emit_postboot(spec: &BoardSpec) -> String {
    let mut out = format!(
        "// Generated PostBoot.ZC — enable={} access={}\n\
         // Immutable after Linux handoff (viewable, writes disabled):\n",
        spec.postboot.enable.as_str(),
        spec.postboot.access
    );
    for name in &spec.postboot.immutable {
        out.push_str("//   ");
        out.push_str(name);
        out.push('\n');
    }
    out.push_str(
        "U0 LinuxHandoff()\n\
         {\n\
         \tPrint(\"POSTBOOT-LIVE\\n\");\n\
         }\n\
         \n\
         U0 SshHolyc()\n\
         {\n\
         \tPrint(\"SSH-HOLYC\\n\");\n\
         }\n\
         \n\
         U0 ViewSection(U8 *name)\n\
         {\n\
         \tPrint(\"VIEW %s\\n\", name);\n\
         }\n\
         \n\
         U0 WriteSection(U8 *name)\n\
         {\n\
         \tPrint(\"WRITE %s\\n\", name);\n\
         }\n",
    );
    for cmd in &spec.postboot.power {
        let tag = match cmd.as_str() {
            "reboot" => "POWER-REBOOT",
            "shutdown" => "POWER-SHUTDOWN",
            "wakeup" => "POWER-WAKEUP",
            other => other,
        };
        let ident = match cmd.as_str() {
            "reboot" => "Reboot",
            "shutdown" => "Shutdown",
            "wakeup" => "Wakeup",
            other => other,
        };
        out.push_str(&format!("\nU0 {ident}()\n{{\n\tPrint(\"{tag}\\n\");\n}}\n"));
    }
    out
}

fn emit_browser_zc(spec: &BoardSpec) -> String {
    let mut out = String::from(
        "// Generated Browser.ZC — lightweight BIOS browser (not Chromium, not goja runtime)\n",
    );
    out.push_str(&format!(
        "// js={} display={} gl={}\n",
        spec.kernel.js, spec.kernel.display, spec.kernel.proxy.gl as u8
    ));
    for name in g6b_webidl::LIVE.iter().take(8) {
        out.push_str("// ");
        out.push_str(&g6b_webidl::marker(name));
        out.push('\n');
    }
    out.push_str("// ");
    out.push_str(&g6b_webidl::marker("Fetch"));
    out.push('\n');
    out.push_str("// ");
    out.push_str(&g6b_webidl::marker("WebGLRenderingContext"));
    out.push('\n');
    if spec.kernel.ui == "svelte-d" {
        out.push_str("// ui=svelte-d (kernel-spec/svelte-d; not LDC, not SvelteKit)\n");
    }
    if spec.kernel.usb.enable {
        out.push_str("// USB-FAT32 flash picker (always); firmware .bin/.elf/.img only\n");
        if spec.kernel.usb.key {
            out.push_str("// USB-FILES FileMgr fat32/ntfs/ext4 (two-pane; fetch /bios/files)\n");
        }
    }
    out.push_str(
        "// browser-UI: fetch /bios/menu/{main,cpu,memory,uncore,devices,boot,settings}\n",
    );
    out.push_str("U0 BrowserInit()\n{\n");
    out.push_str("\tPrint(\"BROWSER-READY\\n\");\n");
    if spec.kernel.wasm.enable {
        out.push_str(&format!("\tPrint(\"{}\\n\");\n", g6b_wasm::MARKER));
    }
    if spec.kernel.ui == "svelte-d" {
        out.push_str("\tPrint(\"SVELTE-LIVE NodeDef\\n\");\n");
        if spec.kernel.usb.key {
            out.push_str("\tPrint(\"SVELTE-LIVE FileMgr\\n\");\n");
        }
    }
    if spec.kernel.usb.enable {
        out.push_str("\tPrint(\"USB-FAT32\\n\");\n");
        if spec.kernel.usb.key {
            out.push_str("\tPrint(\"USB-FILES fat32/ntfs/ext4\\n\");\n");
        }
    }
    out.push_str("}\n");
    out
}

