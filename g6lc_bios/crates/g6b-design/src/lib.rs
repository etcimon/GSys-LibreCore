//! Emit generated ZealC and linker artefacts from a [`BoardSpec`].

#![allow(missing_docs)]

use g6b_spec::{BoardSpec, ExtStatus};

/// All files the design compiler writes for one spec.
#[derive(Debug, Clone)]
pub struct DesignOut {
    pub config_zc: String,
    pub connectors_zc: String,
    pub mem_zc: String,
    pub linker_ld: String,
    pub kmain_zc: String,
    pub adam_zc: String,
    pub postboot_zc: String,
    pub loopback_zc: String,
    pub kstart_s: String,
    pub kints_s: String,
    pub gr_zc: String,
    pub memcpy_s: String,
    pub timer_s: String,
    pub browser_zc: String,
    pub tls_zc: String,
    pub https_zc: String,
    pub gl_glsl: String,
    pub svelte_zc: String,
    pub wasm_jit_s: String,
    pub crypto_s: String,
    pub endpoints_zc: String,
    pub holyc_ui_zc: String,
    pub mbox_dtsi: String,
    pub mbox_h: String,
    pub mbox_c: String,
    pub requirements: String,
}

/// Compile a BoardSpec into generated sources. Never emits RVV unless `spec.rvv_live()`.
pub fn compile(spec: &BoardSpec) -> DesignOut {
    DesignOut {
        config_zc: emit_config(spec),
        connectors_zc: emit_connectors(spec),
        mem_zc: emit_mem(spec),
        linker_ld: emit_linker(spec),
        kmain_zc: emit_kmain(spec),
        adam_zc: emit_adam(spec),
        postboot_zc: emit_postboot(spec),
        loopback_zc: emit_loopback(spec),
        kstart_s: emit_kstart_s(spec),
        kints_s: emit_kints_s(spec),
        gr_zc: emit_gr_zc(spec),
        memcpy_s: emit_memcpy_s(spec),
        timer_s: emit_timer_s(spec),
        browser_zc: emit_browser_zc(spec),
        tls_zc: emit_tls_zc(spec),
        https_zc: emit_https_zc(spec),
        gl_glsl: emit_gl_glsl(spec),
        svelte_zc: emit_svelte_zc(spec),
        wasm_jit_s: emit_wasm_jit_s(spec),
        crypto_s: emit_crypto_s(spec),
        endpoints_zc: emit_endpoints_zc(spec),
        holyc_ui_zc: emit_holyc_ui_zc(spec),
        mbox_dtsi: emit_mbox_dtsi(spec),
        mbox_h: emit_mbox_h(spec),
        mbox_c: emit_mbox_c(spec),
        requirements: emit_requirements(spec),
    }
}

fn flag(st: ExtStatus) -> u32 {
    match st {
        ExtStatus::Live => 1,
        _ => 0,
    }
}

