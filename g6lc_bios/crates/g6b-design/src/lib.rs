fn emit_mbox_c(spec: &BoardSpec) -> String {
    format!(
        "/* Generated g6lc_bios_mbox.c — Linux miscdriver for {chardev} */\n\
         /* Analog: mei / ipmi_si / AppleSMC. Never a network device. */\n\
         /* After NET-DELEGATE both KVM faces (SSH+HolyC, HTML+JS ToHtml) ride this mailbox. */\n\
         #include <linux/miscdevice.h>\n\
         #include <linux/interrupt.h>\n\
         #include <linux/io.h>\n\
         #include <linux/module.h>\n\
         #include <linux/of.h>\n\
         #include <linux/platform_device.h>\n\
         #include <linux/uaccess.h>\n\
         #include \"g6lc_bios_mbox.h\"\n\
         \n\
         struct g6lc_bios {{\n\
         \tvoid __iomem *base;\n\
         \tint irq;\n\
         \tstruct miscdevice misc;\n\
         }};\n\
         \n\
         static irqreturn_t g6lc_bios_irq(int irq, void *data)\n\
         {{\n\
         \tstruct g6lc_bios *p = data;\n\
         \tu32 st = readl(p->base + G6LC_MBOX_STATUS);\n\
         \tif (!(st & G6LC_MBOX_ST_RSP))\n\
         \t\treturn IRQ_NONE;\n\
         \treturn IRQ_HANDLED;\n\
         }}\n\
         \n\
         static ssize_t g6lc_bios_read(struct file *f, char __user *buf, size_t n, loff_t *off)\n\
         {{\n\
         \tstruct g6lc_bios *p = container_of(f->private_data, struct g6lc_bios, misc);\n\
         \tu8 tmp[G6LC_MBOX_RSP_BYTES];\n\
         \tu32 len;\n\
         \tu32 i;\n\
         \t(void)off;\n\
         \tlen = readl(p->base + G6LC_MBOX_LENGTH);\n\
         \tif (len > G6LC_MBOX_RSP_BYTES)\n\
         \t\tlen = G6LC_MBOX_RSP_BYTES;\n\
         \tif (n < len)\n\
         \t\tlen = (u32)n;\n\
         \tfor (i = 0; i < len; i++)\n\
         \t\ttmp[i] = readb(p->base + G6LC_MBOX_RSP + i);\n\
         \tif (copy_to_user(buf, tmp, len))\n\
         \t\treturn -EFAULT;\n\
         \twritel(0, p->base + G6LC_MBOX_STATUS);\n\
         \treturn (ssize_t)len;\n\
         }}\n\
         \n\
         static ssize_t g6lc_bios_write(struct file *f, const char __user *buf, size_t n, loff_t *off)\n\
         {{\n\
         \tstruct g6lc_bios *p = container_of(f->private_data, struct g6lc_bios, misc);\n\
         \tu8 tmp[G6LC_MBOX_CMD_BYTES];\n\
         \tu32 len = n > G6LC_MBOX_CMD_BYTES ? G6LC_MBOX_CMD_BYTES : (u32)n;\n\
         \tu32 i;\n\
         \t(void)off;\n\
         \tif (copy_from_user(tmp, buf, len))\n\
         \t\treturn -EFAULT;\n\
         \tfor (i = 0; i < len; i++)\n\
         \t\twriteb(tmp[i], p->base + G6LC_MBOX_CMD + i);\n\
         \twritel(len, p->base + G6LC_MBOX_LENGTH);\n\
         \twritel(1, p->base + G6LC_MBOX_DOORBELL);\n\
         \treturn (ssize_t)len;\n\
         }}\n\
         \n\
         static const struct file_operations g6lc_bios_fops = {{\n\
         \t.owner = THIS_MODULE,\n\
         \t.read = g6lc_bios_read,\n\
         \t.write = g6lc_bios_write,\n\
         }};\n\
         \n\
         static const struct of_device_id g6lc_bios_mbox_of[] = {{\n\
         \t{{ .compatible = \"{compat}\" }},\n\
         \t{{ }}\n\
         }};\n\
         MODULE_DEVICE_TABLE(of, g6lc_bios_mbox_of);\n\
         \n\
         static int g6lc_bios_probe(struct platform_device *pdev)\n\
         {{\n\
         \tstruct g6lc_bios *p;\n\
         \tstruct resource *res;\n\
         \tint ret;\n\
         \tp = devm_kzalloc(&pdev->dev, sizeof(*p), GFP_KERNEL);\n\
         \tif (!p)\n\
         \t\treturn -ENOMEM;\n\
         \tres = platform_get_resource(pdev, IORESOURCE_MEM, 0);\n\
         \tp->base = devm_ioremap_resource(&pdev->dev, res);\n\
         \tif (IS_ERR(p->base))\n\
         \t\treturn PTR_ERR(p->base);\n\
         \tp->irq = platform_get_irq(pdev, 0);\n\
         \tif (p->irq < 0)\n\
         \t\treturn p->irq;\n\
         \tret = devm_request_irq(&pdev->dev, p->irq, g6lc_bios_irq, 0, \"g6lc-bios\", p);\n\
         \tif (ret)\n\
         \t\treturn ret;\n\
         \twritel(1, p->base + G6LC_MBOX_IRQ_EN);\n\
         \tp->misc.minor = MISC_DYNAMIC_MINOR;\n\
         \tp->misc.name = \"g6lc-bios\";\n\
         \tp->misc.fops = &g6lc_bios_fops;\n\
         \tplatform_set_drvdata(pdev, p);\n\
         \treturn misc_register(&p->misc);\n\
         }}\n\
         \n\
         static void g6lc_bios_remove(struct platform_device *pdev)\n\
         {{\n\
         \tstruct g6lc_bios *p = platform_get_drvdata(pdev);\n\
         \tmisc_deregister(&p->misc);\n\
         }}\n\
         \n\
         static struct platform_driver g6lc_bios_drv = {{\n\
         \t.probe = g6lc_bios_probe,\n\
         \t.remove = g6lc_bios_remove,\n\
         \t.driver = {{\n\
         \t\t.name = \"g6lc-bios-mbox\",\n\
         \t\t.of_match_table = g6lc_bios_mbox_of,\n\
         \t}},\n\
         }};\n\
         \n\
         module_platform_driver(g6lc_bios_drv);\n\
         /* Dual MIT/GPL if built out-of-tree; this generated stub is MIT in-package. */\n\
         MODULE_LICENSE(\"Dual MIT/GPL\");\n\
         MODULE_DESCRIPTION(\"GSys LibreCore BIOS mailbox ({chardev}, irq {irq})\");\n",
        chardev = spec.loopback.chardev,
        compat = spec.loopback.compatible,
        irq = spec.loopback.irq
    )
}

fn emit_requirements(spec: &BoardSpec) -> String {
    let mut out = String::from("# Inferred architecture requirements (from BoardSpec)\n");
    for line in spec.inferred_arch() {
        out.push_str("- ");
        out.push_str(&line);
        out.push('\n');
    }
    if spec.inferred_arch().is_empty() {
        out.push_str("- none (postboot.enable=never)\n");
    }
    out
}

