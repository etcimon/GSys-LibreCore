const RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
];

pub fn clmul_lo(a: u64, b: u64) -> u64 {
    let mut r = 0u64;
    for i in 0..64 {
        if (b >> i) & 1 != 0 {
            r ^= a.wrapping_shl(i);
        }
    }
    r
}

pub fn clmul_hi(a: u64, b: u64) -> u64 {
    let mut r = 0u64;
    for i in 1..64 {
        if (b >> i) & 1 != 0 {
            r ^= a >> (64 - i);
        }
    }
    r
}

pub fn sha256sum0(x: u32) -> u32 {
    x.rotate_right(2) ^ x.rotate_right(13) ^ x.rotate_right(22)
}
pub fn sha256sum1(x: u32) -> u32 {
    x.rotate_right(6) ^ x.rotate_right(11) ^ x.rotate_right(25)
}
pub fn sha256sig0(x: u32) -> u32 {
    x.rotate_right(7) ^ x.rotate_right(18) ^ (x >> 3)
}
pub fn sha256sig1(x: u32) -> u32 {
    x.rotate_right(17) ^ x.rotate_right(19) ^ (x >> 10)
}

fn unpack(lo: u64, hi: u64) -> [u8; 16] {
    let mut s = [0u8; 16];
    for i in 0..8 {
        s[i] = (lo >> (8 * i)) as u8;
        s[8 + i] = (hi >> (8 * i)) as u8;
    }
    s
}

fn pack_lo(s: &[u8; 16]) -> u64 {
    let mut lo = 0u64;
    for i in 0..8 {
        lo |= (s[i] as u64) << (8 * i);
    }
    lo
}

fn shift_rows_sub(s: &mut [u8; 16]) {
    let t = *s;
    s[0] = SBOX[t[0] as usize];
    s[4] = SBOX[t[4] as usize];
    s[8] = SBOX[t[8] as usize];
    s[12] = SBOX[t[12] as usize];
    s[1] = SBOX[t[5] as usize];
    s[5] = SBOX[t[9] as usize];
    s[9] = SBOX[t[13] as usize];
    s[13] = SBOX[t[1] as usize];
    s[2] = SBOX[t[10] as usize];
    s[6] = SBOX[t[14] as usize];
    s[10] = SBOX[t[2] as usize];
    s[14] = SBOX[t[6] as usize];
    s[3] = SBOX[t[15] as usize];
    s[7] = SBOX[t[3] as usize];
    s[11] = SBOX[t[7] as usize];
    s[15] = SBOX[t[11] as usize];
}

fn xtime(a: u8) -> u8 {
    let hi = a >> 7;
    (a << 1) ^ (hi * 0x1b)
}

fn mix_col(c: &mut [u8; 4]) {
    let a0 = c[0];
    let a1 = c[1];
    let a2 = c[2];
    let a3 = c[3];
    c[0] = xtime(a0) ^ xtime(a1) ^ a1 ^ a2 ^ a3;
    c[1] = a0 ^ xtime(a1) ^ xtime(a2) ^ a2 ^ a3;
    c[2] = a0 ^ a1 ^ xtime(a2) ^ xtime(a3) ^ a3;
    c[3] = xtime(a0) ^ a0 ^ a1 ^ a2 ^ xtime(a3);
}

fn mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let o = c * 4;
        let mut col = [s[o], s[o + 1], s[o + 2], s[o + 3]];
        mix_col(&mut col);
        s[o] = col[0];
        s[o + 1] = col[1];
        s[o + 2] = col[2];
        s[o + 3] = col[3];
    }
}

pub fn aes64es(rs1: u64, rs2: u64) -> u64 {
    let mut s = unpack(rs1, rs2);
    shift_rows_sub(&mut s);
    pack_lo(&s)
}

pub fn aes64esm(rs1: u64, rs2: u64) -> u64 {
    let mut s = unpack(rs1, rs2);
    shift_rows_sub(&mut s);
    mix_columns(&mut s);
    pack_lo(&s)
}

pub fn aes64ks1i(rs1: u64, rnum: u32) -> u64 {
    let mut temp = (rs1 >> 32) as u32;
    temp = temp.rotate_right(8);
    let mut bytes = temp.to_le_bytes();
    for b in &mut bytes {
        *b = SBOX[*b as usize];
    }
    bytes[0] ^= RCON[(rnum as usize) % 11];
    let temp = u32::from_le_bytes(bytes);
    ((temp as u64) << 32) | temp as u64
}

pub fn aes64ks2(rs1: u64, rs2: u64) -> u64 {
    let be = (rs1 >> 32) as u32 ^ rs2 as u32;
    let te = be ^ (rs1 as u32);
    ((te as u64) << 32) | be as u64
}
