//! First-party 8x8 bitmap font for the guest DOM paint (`DomPaint`).
//!
//! Same style as `g6b-gr::glyph_row` / `analyze::font_g6lc` — not a VGA ROM.
//! Uppercase-centric ZealOS look: `a`-`z` reuse the `A`-`Z` glyphs. The last
//! entry is the bounded box used for control / DEL / out-of-range bytes.
//! MSB of each byte is the left pixel.

#![allow(missing_docs)]

