/// Flattened table for `.rodata` (`__font`).
pub fn font_bytes() -> Vec<u8> {
    FONT8X8.iter().flat_map(|g| g.iter().copied()).collect()
}

/// Pack one 8-pixel glyph row into a little-endian 4bpp word (high nibble is
/// the left pixel of each byte). Shared by the host-side blit
/// (`analyze::gr_blit_g6lc_ops`) and by the tests that decode a painted plane,
/// so "what the guest wrote" and "what we expect" cannot drift apart.
pub fn pack_row_4bpp(bits: u8, fg: u8, bg: u8) -> u32 {
    let mut w = 0u32;
    for i in 0..8u32 {
        let on = ((bits >> (7 - i)) & 1) == 1;
        let n = if on { fg & 0xf } else { bg & 0xf };
        let shift = (i / 2) * 8 + if i % 2 == 0 { 4 } else { 0 };
        w |= u32::from(n) << shift;
    }
    w
}

/// Glyph index for a guest byte: out-of-range and DEL → box.
pub fn glyph_index(ch: u8) -> usize {
    if !(FONT_FIRST..=0x7E).contains(&ch) {
        FONT_BOX as usize
    } else {
        (ch - FONT_FIRST) as usize
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_printable_ascii_plus_box() {
        assert_eq!(font_bytes().len(), FONT_BYTES);
        assert_eq!(FONT8X8[glyph_index(b' ')][0], 0);
        assert_eq!(FONT8X8[glyph_index(b'G')], G_G);
        assert_eq!(
            FONT8X8[glyph_index(b'g')],
            G_G,
            "lowercase folds to uppercase"
        );
        assert_eq!(FONT8X8[glyph_index(0x7F)], FONT8X8[FONT_BOX as usize]);
        assert_eq!(FONT8X8[glyph_index(0x00)], FONT8X8[FONT_BOX as usize]);
    }

    /// Mirrored pairs must face the right way. Bit 7 is the **left** pixel, so
    /// for `(` the top row sits right of the middle row and for `)` it sits
    /// left — the mirror of that printed `/>` as `\<`.
    #[test]
    fn mirrored_pairs_face_the_right_way() {
        // Leftmost lit pixel of a glyph row (0 = far left).
        fn left(bits: u8) -> u32 {
            u32::from(bits).leading_zeros() - 24
        }
        // Rightmost lit pixel (7 = far right).
        fn right(bits: u8) -> u32 {
            7 - u32::from(bits).trailing_zeros()
        }
        // Curves and angles: the belly of the shape leans away from the apex.
        for (open, close) in [('(', ')'), ('{', '}'), ('<', '>')] {
            let o = FONT8X8[glyph_index(open as u8)];
            let c = FONT8X8[glyph_index(close as u8)];
            assert!(
                left(o[0]) > left(o[3]),
                "{open} must open leftward: {o:02x?}"
            );
            assert!(
                left(c[0]) < left(c[3]),
                "{close} must open rightward: {c:02x?}"
            );
        }
        // Square brackets share the spine column, so the bars are what point:
        // `[` extends right of its spine, `]` extends left of its spine.
        let lb = FONT8X8[glyph_index(b'[')];
        let rb = FONT8X8[glyph_index(b']')];
        assert!(
            right(lb[0]) > right(lb[3]),
            "[ bars extend right: {lb:02x?}"
        );
        assert!(left(rb[0]) < left(rb[3]), "] bars extend left: {rb:02x?}");
        let slash = FONT8X8[glyph_index(b'/')];
        assert!(
            left(slash[0]) > left(slash[6]),
            "/ rises to the right: {slash:02x?}"
        );
        let back = FONT8X8[glyph_index(b'\\')];
        assert!(
            left(back[0]) < left(back[6]),
            "\\ falls to the right: {back:02x?}"
        );
    }

    #[test]
    fn packing_puts_the_msb_on_the_left() {
        // 0x80 = only the leftmost pixel → high nibble of the first byte.
        assert_eq!(pack_row_4bpp(0x80, 0xF, 0) & 0xFF, 0xF0);
        // 0x01 = only the rightmost pixel → low nibble of the last byte.
        assert_eq!(pack_row_4bpp(0x01, 0xF, 0) >> 24, 0x0F);
    }
}
