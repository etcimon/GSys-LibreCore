/// Flattened table for `.rodata` (`__font`).
pub fn font_bytes() -> Vec<u8> {
    FONT8X8.iter().flat_map(|g| g.iter().copied()).collect()
}

/// Glyph index for a guest byte: out-of-range and DEL → box.
pub fn glyph_index(ch: u8) -> usize {
    if !(FONT_FIRST..=0x7E).contains(&ch) {
        FONT_BOX as usize
    } else {
        (ch - FONT_FIRST) as usize
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_printable_ascii_plus_box() {
        assert_eq!(font_bytes().len(), FONT_BYTES);
        assert_eq!(FONT8X8[glyph_index(b' ')][0], 0);
        assert_eq!(FONT8X8[glyph_index(b'G')], G_G);
        assert_eq!(
            FONT8X8[glyph_index(b'g')],
            G_G,
            "lowercase folds to uppercase"
        );
        assert_eq!(FONT8X8[glyph_index(0x7F)], FONT8X8[FONT_BOX as usize]);
        assert_eq!(FONT8X8[glyph_index(0x00)], FONT8X8[FONT_BOX as usize]);
    }
}
