// Elaborated `CVA6Cfg` snapshot for sv-timing's width inference.
//
// The host param-map used to carry XLEN only, so every sv-timing width that
// depends on a derived cfg field (`CVA6Cfg.TRANS_ID_BITS`, `NrHarts`,
// `INSTR_PER_FETCH`, `NR_SB_ENTRIES`, …) stayed unresolved and the node was
// costed at the reference width: a 3-bit commit pointer increment was billed
// like a 32-bit adder. `build_config_pkg::build_config` is a 500-line function
// — re-implementing it in TypeScript would drift — so this module has the
// elaborator evaluate it:
//
//   1. parse `cva6_cfg_t` in core/include/config_pkg.sv for its `int unsigned`
//      / `int` / `bit` fields;
//   2. generate a probe module with one output port per field, declared
//      `logic [CVA6Cfg.<Field>:0]` (width = value + 1, so 0 is representable);
//   3. `read_slang` the three config packages + the probe, `write_json`, and
//      read each port's bit count back.
//
// The result is written next to the param-map and merged into it as
// `CVA6Cfg.<Field>` / `cva6_cfg.<Field>` integer keys. No simulation, no C++
// build: yosys-slang elaboration only (~seconds).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { run } from "../platform/exec.ts";
import { hasWsl, windowsPathToWsl, wslCommand } from "../platform/wsl.ts";
import type { PlatformContext } from "../context.ts";
import { edaEnv, posixPath, type EdaPaths } from "./eda.ts";

/** `int unsigned` / `int` / `bit` fields of `cva6_cfg_t`, in declaration order. */
export function cvaCfgIntFields(configPkgText: string): string[] {
  const end = configPkgText.indexOf("} cva6_cfg_t;");
  if (end < 0) return [];
  const start = configPkgText.lastIndexOf("typedef struct packed {", end);
  if (start < 0) return [];
  const block = configPkgText.slice(start, end);
  const out: string[] = [];
  for (const raw of block.split(/\r?\n/)) {
    const line = raw.replace(/\/\/.*$/, "").trim();
    const m = line.match(/^(?:int\s+unsigned|int|bit)\s+([A-Za-z_][A-Za-z0-9_]*)\s*;$/);
    if (m?.[1]) out.push(m[1]);
  }
  return out;
}

/** Probe module text: one output per field, width = field value + 1. */
export function cfgProbeSource(fields: string[], userCfgPkg: string): string {
  const ports = fields.map((f) => `  output logic [CVA6Cfg.${f}:0] p_${f}`).join(",\n");
  const drives = fields.map((f) => `  assign p_${f} = '0;`).join("\n");
  return [
    "// Generated by build-platform cfgSnapshot — not a design file.",
    "module g6lc_cfg_probe #(",
    `  parameter config_pkg::cva6_cfg_t CVA6Cfg = build_config_pkg::build_config(${userCfgPkg}::cva6_cfg)`,
    ") (",
    ports,
    ");",
    drives,
    "endmodule",
    "",
  ].join("\n");
}

/** Field values from yosys `write_json` port bit counts (width − 1). */
export function cfgValuesFromYosysJson(jsonText: string, fields: string[]): Record<string, number> {
  const doc = JSON.parse(jsonText) as { modules?: Record<string, { ports?: Record<string, { bits?: unknown[] }> }> };
  const mod = doc.modules?.["g6lc_cfg_probe"];
  const out: Record<string, number> = {};
  if (!mod?.ports) return out;
  for (const f of fields) {
    const bits = mod.ports[`p_${f}`]?.bits;
    if (Array.isArray(bits) && bits.length >= 1) out[f] = bits.length - 1;
  }
  return out;
}

export interface CfgSnapshot {
  /** `CVA6Cfg.<Field>` and `cva6_cfg.<Field>` → value. */
  entries: Record<string, number>;
  /** Snapshot JSON path. */
  path: string;
  /** Fields the probe could not report (missing port in the JSON). */
  missing: string[];
  detail: string;
}

/**
 * Elaborate the target's `CVA6Cfg` through yosys-slang and return the integer
 * fields. `null` when the toolchain or the config package is not available
 * (the caller keeps the XLEN-only map and says so).
 */
export async function snapshotCvaCfg(
  ctx: PlatformContext,
  paths: EdaPaths,
  target: string,
  outDir: string,
): Promise<CfgSnapshot | null> {
  const configPkg = join(ctx.repoRoot, "core", "include", "config_pkg.sv");
  const buildPkg = join(ctx.repoRoot, "core", "include", "build_config_pkg.sv");
  const targetPkg = join(ctx.repoRoot, "core", "include", `${target}_config_pkg.sv`);
  if (!existsSync(configPkg) || !existsSync(buildPkg) || !existsSync(targetPkg)) return null;
  // A Yosys with `read_slang`: the suite's when the frontend is integrated,
  // else the managed formal prefix (a Linux ELF — through WSL on Windows,
  // like the formal gate and the sta-rtl mapping do).
  const managedYosys = join(ctx.tools.formalBin, "yosys");
  let yosys: string;
  let viaWsl = false;
  if (existsSync(paths.yosys) && paths.slangIntegrated) {
    yosys = paths.yosys;
  } else if (existsSync(managedYosys)) {
    yosys = managedYosys;
    viaWsl = ctx.host.os === "windows";
    if (viaWsl && !hasWsl()) return null;
  } else {
    return null;
  }
  const fields = cvaCfgIntFields(readFileSync(configPkg, "utf8"));
  if (fields.length === 0) return null;
  const pkgName = readFileSync(targetPkg, "utf8").match(/^package\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/m)?.[1] ?? "cva6_config_pkg";

  const dir = join(outDir, "cfg-probe");
  mkdirSync(dir, { recursive: true });
  const probe = join(dir, "g6lc_cfg_probe.sv");
  const jsonOut = join(dir, "probe.json");
  const flist = join(dir, "probe.f");
  writeFileSync(probe, cfgProbeSource(fields, pkgName), "utf8");
  const p = async (x: string) => (viaWsl ? windowsPathToWsl(x) : posixPath(x));
  // riscv_pkg / ariane_pkg are not needed: build_config reads only its own
  // packages. Keep the list minimal so the probe is seconds, not a core parse.
  const files = [configPkg, targetPkg, buildPkg, probe];
  writeFileSync(flist, (await Promise.all(files.map(p))).join("\n") + "\n", "utf8");
  const defines = ctx.config.verify.synthDefines.map((d) => `-D${d}`).join(" ");
  const script = `read_slang -f ${await p(flist)} --top g6lc_cfg_probe --single-unit ${defines}; hierarchy -top g6lc_cfg_probe; write_json ${await p(jsonOut)}`;
  let res;
  if (viaWsl) {
    const ys = await windowsPathToWsl(yosys);
    res = await run("wsl", wslCommand(`${JSON.stringify(ys)} -q -p ${JSON.stringify(script)}`), {
      cwd: ctx.repoRoot, stdio: "capture", allowFailure: true, dryRun: ctx.dryRun, logger: ctx.logger,
    });
  } else {
    res = await run(yosys, ["-q", "-p", script], {
      cwd: ctx.repoRoot, env: edaEnv(ctx, paths, target), stdio: "capture", allowFailure: true, dryRun: ctx.dryRun, logger: ctx.logger,
    });
  }
  writeFileSync(join(dir, "probe.log"), `exit=${res.code}\n${res.stdout}\n${res.stderr}\n`, "utf8");
  if (ctx.dryRun) return null;
  if (!res.ok || !existsSync(jsonOut)) {
    ctx.logger.warn(`cfg snapshot: yosys-slang probe failed (exit ${res.code}); widths depending on CVA6Cfg stay unresolved (see ${posixPath(join(dir, "probe.log"))})`);
    return null;
  }
  const values = cfgValuesFromYosysJson(readFileSync(jsonOut, "utf8"), fields);
  const entries: Record<string, number> = {};
  for (const [f, v] of Object.entries(values)) {
    entries[`CVA6Cfg.${f}`] = v;
    entries[`cva6_cfg.${f}`] = v;
  }
  const missing = fields.filter((f) => !(f in values));
  const snapshotPath = join(outDir, "cfg-snapshot.json");
  writeFileSync(
    snapshotPath,
    JSON.stringify({ target, package: pkgName, source: "yosys-slang probe port widths", fields: values, missing }, null, 2) + "\n",
    "utf8",
  );
  return {
    entries,
    path: posixPath(snapshotPath),
    missing,
    detail: `${Object.keys(values).length}/${fields.length} CVA6Cfg fields elaborated${missing.length ? ` (${missing.length} missing)` : ""}`,
  };
}
