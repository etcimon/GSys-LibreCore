"""Stage a single sv-timing emit file into the hyp tree.

Usage: python tools/stage_emit.py <emit_rel> <hyp_rel> <MODE>
  emit_rel: path under <prov>/emit/core-8fo4/corrected/
  hyp_rel : path under hyp_redesign_core_8fo4/
  MODE    : AS-IS | ADAPTED | REWRITTEN

Copies the emit file, applies the identity rename, and prepends the
`// hyp8 provenance:` line. The emit's own SPDX/banner is preserved below it.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rename import apply_rename  # noqa: E402

WS = Path(__file__).resolve().parent.parent
HYP = WS.parent / "hyp_redesign_core_8fo4"
PROV = WS.parents[1] / "build" / "sv-timing" / "hyp8-src" \
    / "emit" / "core-8fo4" / "corrected"


def main():
    emit_rel, hyp_rel, mode = sys.argv[1], sys.argv[2], sys.argv[3]
    src = PROV / emit_rel
    dst = HYP / hyp_rel
    text = src.read_text(encoding="utf-8")
    text = apply_rename(text)
    # drop the emit's generated banner lines (provenance is in our header)
    lines = text.splitlines()
    out = []
    for ln in lines:
        if ln.startswith("// Generated by sv-timing") or \
           ln.startswith("// DO NOT commit without human review"):
            continue
        out.append(ln)
    dst.parent.mkdir(parents=True, exist_ok=True)
    hdr = f"// hyp8 provenance: {mode} (sv-timing emit at the 8-FO4 budget)\n"
    dst.write_text(hdr + "\n".join(out) + "\n", encoding="utf-8")
    print(f"{hyp_rel}: staged ({mode})")


if __name__ == "__main__":
    main()


# keep tools/ free of compiled bytecode (the identity grep covers every
# file type — *.pyc embeds the original source tokens)
def _cleanup_pycache():
    import pathlib as _pl
    import shutil as _sh
    _d = _pl.Path(__file__).resolve().parent
    _sh.rmtree(_d / "__pycache__", ignore_errors=True)
    for _f in _d.glob("*.pyc"):
        try:
            _f.unlink()
        except OSError:
            pass


_cleanup_pycache()
