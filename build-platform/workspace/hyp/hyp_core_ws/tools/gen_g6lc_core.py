# -------------------------------------------------- per-instance edits
def edit_instance(text, inst_anchor, inst_end, fn):
    """Apply fn() to the block from inst_anchor up to inst_end (exclusive)."""
    i = text.find(inst_anchor)
    assert i > 0, f"anchor not found: {inst_anchor!r}"
    j = text.find(inst_end, i)
    assert j > i, f"end not found after {inst_anchor!r}: {inst_end!r}"
    return text[:i] + fn(text[i:j]) + text[j:]

def add_param(block):
    out, n = re.subn(r"\.G6LCCfg\s*\(\s*G6LCCfg\s*\)",
                     ".G6LCCfg(G6LCCfg),\n      .HypCfg (HypCfg)", block, count=1)
    assert n == 1, "no G6LCCfg param line"
    return out

# frontend: HypCfg + held commit pc
