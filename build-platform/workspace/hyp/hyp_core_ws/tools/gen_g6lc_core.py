# id_stage / issue_stage / ex_stage / commit_stage / csr bank / perf / ctrl
def conns(after_anchor, insertion):
    def f(block):
        assert after_anchor in block, f"conn anchor {after_anchor!r}"
        return block.replace(after_anchor, after_anchor + insertion, 1)
    return f

